import assert from 'node:assert/strict';
const presets = Object.fromEntries(['a','b','c','d','e','f'].map(k => [k, {}]));
let saved = null;
globalThis.localStorage = { getItem: () => saved, setItem: (_, value) => { saved = value; } };
const history = await import('../public/js/stamp-history.mjs');
assert.deepEqual(history.getRecentStamps(presets), []);
for (const key of Object.keys(presets)) history.rememberStamp(key, presets);
assert.deepEqual(history.getRecentStamps(presets), ['f','e','d','c','b']);
history.rememberStamp('d', presets);
history.rememberStamp('toString', presets);
assert.deepEqual(history.getRecentStamps(presets), ['d','f','e','c','b']);
const fresh = await import('../public/js/stamp-history.mjs?reload');
assert.deepEqual(fresh.getRecentStamps(presets), ['d','f','e','c','b']);
saved = '["a","a","unknown",null,"b"]';
assert.deepEqual(history.getRecentStamps(presets), ['a','b']);
saved = '{"not":"an array"}';
assert.deepEqual(history.getRecentStamps(presets), []);
saved = '{broken';
assert.deepEqual(history.getRecentStamps(presets), []);
saved = '["a"]';
globalThis.localStorage.setItem = () => { throw new Error('quota'); };
history.rememberStamp('b', presets);
history.rememberStamp('c', presets);
assert.deepEqual(history.getRecentStamps(presets), ['c','b','a']);
globalThis.localStorage.getItem = () => { throw new Error('blocked'); };
history.rememberStamp('e', presets);
assert.deepEqual(history.getRecentStamps(presets), ['e','c','b','a']);
delete globalThis.localStorage;
console.log('Stamp history: cap, order, deduplication, persistence, validation, quota and blocked storage passed.');
